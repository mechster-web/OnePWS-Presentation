/**
 * Measures the recorded narration and writes the per-chapter totals that the
 * navigation uses for "N min remaining".
 *
 * Without this the countdown runs on the hand-written durationMs estimate in
 * chapters.ts, which drifts away from what a listener actually hears. A chapter
 * with narration is timed from its own audio: the chapter track if there is one,
 * otherwise the sum of its walkthrough segments.
 *
 *   node scripts/measure-narration.mjs [--check]
 *
 * --check reports drift without writing, for use in review.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import esbuild from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_DIR = path.join(ROOT, "public");
const OUTPUT = path.join(ROOT, "src", "content", "narrationDurations.ts");
const CHECK_ONLY = process.argv.includes("--check");

const BITRATES = [0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320];
const SAMPLE_RATES = [44100, 48000, 32000];

/**
 * Reads the duration straight out of the MP3 rather than decoding it: a Xing
 * header gives the exact frame count, and a constant-bitrate file can be
 * divided by its bitrate.
 */
function durationMs(file) {
  const buffer = readFileSync(file);

  let start = 0;
  if (buffer.slice(0, 3).toString("latin1") === "ID3") {
    start = 10 + ((buffer[6] & 0x7f) << 21 | (buffer[7] & 0x7f) << 14 | (buffer[8] & 0x7f) << 7 | (buffer[9] & 0x7f));
  }

  for (let i = start; i < buffer.length - 4; i += 1) {
    if (buffer[i] !== 0xff || (buffer[i + 1] & 0xe0) !== 0xe0) {
      continue;
    }

    const bitrate = BITRATES[(buffer[i + 2] >> 4) & 0x0f];
    const sampleRate = SAMPLE_RATES[(buffer[i + 2] >> 2) & 0x03];
    if (!bitrate || !sampleRate) {
      continue;
    }

    const xing = buffer.indexOf("Xing", i, "latin1");
    const info = buffer.indexOf("Info", i, "latin1");
    const tag = xing >= 0 && xing < i + 200 ? xing : info >= 0 && info < i + 200 ? info : -1;
    if (tag >= 0 && (buffer[tag + 7] & 0x01) === 1) {
      const frames = buffer.readUInt32BE(tag + 8);
      return Math.round((frames * 1152 * 1000) / sampleRate);
    }

    return Math.round(((buffer.length - start) * 8) / bitrate);
  }

  return 0;
}

async function loadModule(entry) {
  const bundle = await esbuild.build({
    entryPoints: [entry],
    absWorkingDir: ROOT,
    bundle: true,
    format: "esm",
    platform: "node",
    write: false,
    logLevel: "silent",
    define: {
      "import.meta.env.DEV": "false",
      "import.meta.env.PROD": "true",
      "import.meta.env.MODE": '"production"',
    },
  });
  const encoded = Buffer.from(bundle.outputFiles[0].text).toString("base64");
  return import("data:text/javascript;base64," + encoded);
}

const { voiceovers } = await loadModule("src/content/voiceovers.ts");
const { slideNarrationSets } = await loadModule("src/content/slideNarration.ts");
const { enabledChapters } = await loadModule("src/content/chapters.ts");

const measured = {};

// A walkthrough is the closest match to what the audience sits through.
for (const [chapterId, segments] of Object.entries(slideNarrationSets)) {
  let total = 0;
  let complete = true;
  for (const segment of segments) {
    const file = path.join(PUBLIC_DIR, segment.file.replace(/^\//, ""));
    if (!existsSync(file)) {
      complete = false;
      break;
    }
    total += durationMs(file);
  }
  if (complete && total > 0) {
    measured[chapterId] = total;
  }
}

for (const voiceover of voiceovers) {
  if (voiceover.scope !== "chapter" || measured[voiceover.ownerId] || !voiceover.plannedFile) {
    continue;
  }
  const file = path.join(PUBLIC_DIR, voiceover.plannedFile.replace(/^\//, ""));
  if (existsSync(file)) {
    const value = durationMs(file);
    if (value > 0) {
      measured[voiceover.ownerId] = value;
    }
  }
}

const rows = Object.entries(measured).sort(([a], [b]) => a.localeCompare(b));
const estimateFor = (id) => enabledChapters.find((chapter) => chapter.id === id)?.durationMs ?? 0;

console.log(`${rows.length} chapter${rows.length === 1 ? "" : "s"} with recorded narration:\n`);
for (const [id, value] of rows) {
  const estimate = estimateFor(id);
  const drift = estimate ? ` (estimate ${(estimate / 1000).toFixed(0)}s)` : "";
  console.log(`  ${id.padEnd(32)} ${(value / 1000).toFixed(1)}s${drift}`);
}

if (CHECK_ONLY) {
  console.log("\n--check: nothing written.");
  process.exit(0);
}

const body = `/**
 * Generated by scripts/measure-narration.mjs -- do not edit by hand.
 *
 * Real length of the recorded narration per chapter, used so the remaining-time
 * readout counts what the audience will actually hear instead of an estimate.
 * Run \`npm run voiceover:durations\` after adding or replacing audio.
 */
export const narrationDurationMs: Record<string, number> = {
${rows.map(([id, value]) => `  "${id}": ${value},`).join("\n")}
};

export function narrationDurationFor(chapterId: string) {
  return narrationDurationMs[chapterId] ?? null;
}
`;

writeFileSync(OUTPUT, body);
console.log(`\nWrote ${path.relative(ROOT, OUTPUT).replace(/\\/g, "/")}`);
process.exit(0);
